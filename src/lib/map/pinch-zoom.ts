/**
 * Щипок на трекпаде над картой — чистый расчёт без карты и браузера.
 *
 * Chrome и Firefox присылают щипок как прокрутку колеса с зажатым Ctrl
 * (маленькие deltaY, десятки событий за жест), Safari — отдельными
 * gesture-событиями с накопленным масштабом scale. Карта меняет масштаб
 * целыми уровнями, поэтому оба потока приводятся к «на сколько уровней».
 */

/**
 * Сколько накопленной прокрутки даёт один уровень масштаба. Браузеры считают
 * масштаб щипка как exp(−deltaY / 100), так что удвоение (один уровень карты)
 * — это около 69 единиц; берём чуть меньше, чтобы карта откликалась охотнее.
 * Встроенная прокрутка Leaflet для трекпада не годится: она меняет уровень
 * на каждое событие, и карта улетает.
 */
export const PINCH_PER_ZOOM_LEVEL = 60;

export type PinchStep = {
  /** +1 — приблизить, −1 — отдалить, 0 — жест ещё не набрал на уровень */
  direction: 1 | -1 | 0;
  /** накопленная прокрутка после шага (при смене уровня обнуляется) */
  rest: number;
};

/**
 * Очередное событие колеса с Ctrl: накопленное + новая дельта → шаг масштаба.
 * Пальцы раздвигаются — deltaY отрицательный — карта приближается.
 */
export function pinchStep(accumulated: number, deltaY: number): PinchStep {
  const total = accumulated + deltaY;
  if (Math.abs(total) < PINCH_PER_ZOOM_LEVEL) {
    return { direction: 0, rest: total };
  }
  return { direction: total < 0 ? 1 : -1, rest: 0 };
}

/**
 * Safari: масштаб жеста (1 — как было, 2 — вдвое крупнее) → на сколько целых
 * уровней сдвинуть карту от начала жеста. Уровень карты — удвоение.
 */
export function gestureZoomDelta(scale: number): number {
  if (!Number.isFinite(scale) || scale <= 0) {
    return 0;
  }
  // + 0 превращает «минус ноль» в обычный ноль
  return Math.round(Math.log2(scale)) + 0;
}

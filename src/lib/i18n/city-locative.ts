/**
 * «в Паттайе» — город в предложном падеже для русских заголовков
 * («Другие Skippy Land в Паттайе», «День рождения ребёнка в Паттайе»).
 * У City формы падежа нет; словарик здесь — одно место вместо частных
 * случаев по страницам. Неизвестный город — «в {имя}»: это лучше, чем
 * угадывать окончание и получить «в Хуахинe».
 */

const LOCATIVE_RU: Record<string, string> = {
  Паттайя: "в Паттайе",
  Бангкок: "в Бангкоке",
  Пхукет: "на Пхукете",
  Хуахин: "в Хуахине",
  Чиангмай: "в Чиангмае",
  Самуи: "на Самуи",
  Краби: "в Краби",
};

export function cityLocativeRu(cityName: string): string {
  return LOCATIVE_RU[cityName.trim()] ?? `в ${cityName}`;
}

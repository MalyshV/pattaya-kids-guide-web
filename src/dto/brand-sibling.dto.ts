/**
 * Строка блока «Другие {сеть} в {городе}» на странице точки сети
 * (docs/CHAINS_PLAN.md): другая точка той же сети в том же городе, уже
 * локализованная и с посчитанным расстоянием от текущей.
 */
export type BrandSiblingDto = {
  slug: string;
  /** отображаемое имя: бренд · метка точки на языке страницы */
  name: string;
  /** по прямой от текущей точки, метры */
  distanceM: number;
  /** ближе 150 м — «в этом же ТЦ» вместо расстояния */
  sameMall: boolean;
  /** минимальная детская цена входа; null = цены не занесены */
  entryFrom: { amount: number; currency: string } | null;
  /** подпись первой строки цены («Сеанс 40 мин»); null = цен нет */
  sessionLabel: string | null;
  /** только подтверждённое «да» — «уточняется» и «нет» в строку не идут */
  canLeaveChild: boolean;
  /** фраза от руки, чем точка отличается; null = не написана */
  note: string | null;
};
